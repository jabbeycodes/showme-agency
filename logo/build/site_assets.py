"""Generate the site's brand assets from the logo construction:
  scripts/brand.mjs           inline header (animated) + footer (reversed) lockups
  static/favicon.svg|ico, apple-touch-icon.png, icon-192/512(.png), icon-512-maskable.png
  static/og-image.png         1200x630 social card
Run from logo/build: python3 site_assets.py
"""
import os, re, io, json
from compose import horizontal, stacked, TAG_PRIMARY
from favicon import favicon
from make import OUT
from playwright.sync_api import sync_playwright
from PIL import Image

ROOT = os.path.abspath(os.path.join(OUT, '..'))
STATIC = os.path.join(ROOT, 'static')

def inline(svg, cls, h):
    svg = re.sub(r'<title[^>]*>.*?</title>', '', svg)
    svg = svg.replace(' role="img" aria-labelledby="t"', '')
    svg = re.sub(r'(-?\d+\.\d+)', lambda m: ('%.1f' % float(m.group(1))).rstrip('0').rstrip('.'), svg)
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
    w = round(h * vb[2] / vb[3])
    svg = svg.replace('<svg xmlns="http://www.w3.org/2000/svg" ',
                      f'<svg class="{cls}" width="{w}" height="{h}" aria-hidden="true" focusable="false" ', 1)
    return svg.strip(), w

def brand_module():
    hdr, hw = inline(horizontal('color', 'bh'), 'brand-logo sm-anim', 48)
    ftr, fw = inline(horizontal('reverse', 'bf'), 'brand-logo', 52)
    js = ('// GENERATED by logo/build/site_assets.py — do not edit by hand.\n'
          '// Inline SVG lockups of the ShowMe logo (header: animated colour; footer: reversed, static).\n'
          f'export const BRAND_HEADER = {json.dumps(hdr)};\n'
          f'export const BRAND_FOOTER = {json.dumps(ftr)};\n'
          f'export const BRAND_SIZE = {{ header: [{hw}, 48], footer: [{fw}, 52] }};\n')
    open(os.path.join(ROOT, 'scripts', 'brand.mjs'), 'w').write(js)
    print('brand.mjs', len(hdr), len(ftr), hw, fw)

def render(page, html, w, h, path, transparent=False):
    page.set_viewport_size({'width': w, 'height': h})
    page.set_content(html); page.wait_for_timeout(150)
    page.screenshot(path=path, omit_background=transparent)

def icons(page):
    tile = favicon('tile', pad=64*0.12)
    open(os.path.join(STATIC, 'favicon.svg'), 'w').write(tile)
    full = favicon('tile', pad=64*0.16, rx=0)               # apple-touch: full bleed, iOS rounds it
    mask = favicon('tile', box=512, pad=512*0.25, rx=0)      # maskable: S inside the 80% safe circle
    def sized(svg, s): return svg.replace('<svg ', f'<svg width="{s}" height="{s}" ', 1)
    body = lambda svg, s: f'<html><body style="margin:0;background:transparent">{sized(svg, s)}</body></html>'
    tmp = {}
    for s in (16, 32, 48):
        p = f'/tmp/fav{s}.png'; render(page, body(tile, s), s, s, p, True); tmp[s] = p
    ims = [Image.open(tmp[s]).convert('RGBA') for s in (16, 32, 48)]
    ims[0].save(os.path.join(STATIC, 'favicon.ico'), sizes=[(16, 16), (32, 32), (48, 48)], append_images=ims[1:])
    render(page, body(tile, 192), 192, 192, os.path.join(STATIC, 'icon-192.png'), True)
    render(page, body(tile, 512), 512, 512, os.path.join(STATIC, 'icon-512.png'), True)
    render(page, body(full, 180), 180, 180, '/tmp/apple.png')
    Image.open('/tmp/apple.png').convert('RGB').save(os.path.join(STATIC, 'apple-touch-icon.png'), optimize=True)
    render(page, body(mask, 512), 512, 512, '/tmp/mask.png')
    Image.open('/tmp/mask.png').convert('RGB').save(os.path.join(STATIC, 'icon-512-maskable.png'), optimize=True)
    for f in ('icon-192.png', 'icon-512.png'):
        p = os.path.join(STATIC, f); Image.open(p).save(p, optimize=True)
    # keep the logo/favicon folder in step
    for f in ('icon-192.png', 'icon-512-maskable.png'):
        Image.open(os.path.join(STATIC, f)).save(os.path.join(OUT, 'favicon', f))

def og(page):
    logo = stacked('reverse', None, 'og')
    html = f'''<html><head><style>
body{{margin:0;width:1200px;height:630px;background:#0b1b33;font-family:Inter,sans-serif;color:#fff;display:flex;align-items:center;overflow:hidden;position:relative}}
.l{{width:430px;padding-left:70px;flex:none}} .l svg{{width:380px;height:auto;display:block}}
.r{{padding:0 70px 0 50px;border-left:2px solid rgba(255,255,255,.14);margin-left:30px}}
h1{{font-size:50px;line-height:1.12;letter-spacing:-.02em;margin:0 0 26px;font-weight:800}}
h1 span{{color:#52c8ff}}
p{{font-size:21px;line-height:1.5;color:#b4c0d3;margin:0;font-weight:500}}
.u{{position:absolute;left:0;right:0;bottom:0;height:8px;background:linear-gradient(90deg,#0b5ee0,#1aaef6)}}
.d{{position:absolute;right:70px;bottom:34px;font-size:18px;color:#8fa2bf;font-weight:600;letter-spacing:.02em}}
</style></head><body><div class="l">{logo}</div><div class="r">
<h1>Technology That Runs Your Business. <span>Solutions That Power Its Growth.</span></h1>
<p>Managed IT, digital marketing, AI automation and software &amp; consulting from one technology partner.</p></div>
<div class="d">agency.showmeworld.app</div><div class="u"></div></body></html>'''
    render(page, html, 1200, 630, '/tmp/og.png')
    Image.open('/tmp/og.png').convert('RGB').save(os.path.join(STATIC, 'og-image.png'), optimize=True)

if __name__ == '__main__':
    brand_module()
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path='/usr/bin/google-chrome')
        pg = b.new_page()
        icons(pg); og(pg)
        b.close()
    print('ok')
